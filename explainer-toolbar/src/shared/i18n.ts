const tables = { en, ar } as const;
export type Lang = keyof typeof tables;

let lang: Lang = "en";
const subs = new Set<() => void>();

export function resolveLang(pref: "system" | Lang): Lang {
  if (pref !== "system") return pref;
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  return nav.toLowerCase().startsWith("ar") ? "ar" : "en";
}

export function setLanguage(pref: "system" | Lang): void {
  const next = resolveLang(pref);
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  }
  if (next === lang) return;
  lang = next;
  subs.forEach((f) => f());
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = tables[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (f) => {
      subs.add(f);
      return () => subs.delete(f);
    },
    () => lang,
  );
}

export function isRtl(): boolean {
  return lang === "ar";
}
