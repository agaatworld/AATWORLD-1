#!/usr/bin/env node
/* =============================================================================
   AAT World v3 · tools/build.js (architect; builders run it, never edit it)
   Usage:  node tools/build.js            (from anywhere)
           node tools/build.js --sync-shell   also refresh the static first-frame header inside shell.html
   Writes (each through a temp file + rename, so builders can run it at the same time):
     data/data.js   window.AAT_DATA_V3 = <data.json>;  window.AAT_FILES = [every shipped img/ path];
     page.html      the publishable FRAGMENT: shell.html with every local stylesheet inlined into ONE <style>
                    and every local script inlined into ONE <script> (in order); Google Fonts links kept;
                    the static first-frame header (Arabic) re-rendered from js/app.js.
     index.html     the publish skeleton (doctype, html lang=ar dir=rtl, charset, viewport-fit=cover, reset)
                    around page.html, for local testing at http://localhost:8790/index.html
   Checks: page.html has no doctype/html/head/body tags, starts with <title>, one <style>, one <script>,
   size < 16 MB, every img/ path referenced in the code exists.
============================================================================= */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const ROOT = path.resolve(__dirname, '..');
const rel = p => path.join(ROOT, p);
const kb = n => (n / 1024).toFixed(1) + ' KB';

function writeAtomic(file, content) {
  const tmp = file + '.' + process.pid + '.' + Date.now() + '.' + Math.random().toString(36).slice(2) + '.tmp';
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, file);
}
function walk(dir, out) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f), st = fs.statSync(p);
    if (st.isDirectory()) walk(p, out); else out.push(path.relative(ROOT, p).split(path.sep).join('/'));
  }
  return out;
}
const problems = [];

/* (a) data/data.js ------------------------------------------------------- */
const json = JSON.parse(fs.readFileSync(rel('data/data.json'), 'utf8'));
const files = walk(rel('img'), []).sort();
const safe = s => s.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');
const dataJs = '/* generated by tools/build.js from data/data.json — do not edit */\n' +
  'window.AAT_DATA_V3 = ' + safe(JSON.stringify(json)) + ';\n' +
  'window.AAT_FILES = ' + JSON.stringify(files) + ';\n';
writeAtomic(rel('data/data.js'), dataJs);

/* (b) page.html ----------------------------------------------------------- */
let shell = fs.readFileSync(rel('shell.html'), 'utf8');

// static first-frame header, rendered by the real header() of js/app.js in Arabic
function firstFrameHeader() {
  const win = { console, location: { search: '', hash: '' }, navigator: {}, setTimeout, clearTimeout };
  win.window = win;
  win.document = { readyState: 'loading', addEventListener() {}, getElementById() { return null; }, querySelector() { return null }, querySelectorAll() { return []; }, documentElement: { classList: { toggle() {}, add() {}, remove() {} } } };
  const ctx = vm.createContext(win);
  vm.runInContext(dataJs, ctx, { filename: 'data.js' });
  vm.runInContext(fs.readFileSync(rel('js/app.js'), 'utf8'), ctx, { filename: 'app.js' });
  return win.AAT.ui.header();
}
const FF = /(<!--ff:header-->)([\s\S]*?)(<!--\/ff:header-->)/;
try {
  const hdr = firstFrameHeader();
  if (!FF.test(shell)) problems.push('shell.html has no <!--ff:header--> … <!--/ff:header--> markers');
  shell = shell.replace(FF, (m, a, b, c) => a + hdr + c);
  if (process.argv.includes('--sync-shell')) {
    const src = fs.readFileSync(rel('shell.html'), 'utf8');
    writeAtomic(rel('shell.html'), src.replace(FF, (m, a, b, c) => a + hdr + c));
    console.log('shell.html first-frame header refreshed');
  }
} catch (e) {
  problems.push('first-frame header could not be rendered (kept the copy in shell.html): ' + e.message);
}

const isLocal = href => !/^(https?:)?\/\//i.test(href);
const styles = [], scripts = [];
let markup = shell;
// stylesheets: <link rel="stylesheet" href="css/x.css">
markup = markup.replace(/<link\b[^>]*rel=["']stylesheet["'][^>]*>\s*/gi, tag => {
  const href = (tag.match(/href=["']([^"']+)["']/i) || [])[1];
  if (!href || !isLocal(href)) return tag;
  const css = fs.readFileSync(rel(href.split('?')[0]), 'utf8');
  styles.push('/* ===== ' + href + ' ===== */\n' + css.trim());
  return styles.length === 1 ? '@@STYLE@@\n' : '';
});
// scripts: <script src="js/x.js"></script>
markup = markup.replace(/<script\b[^>]*src=["']([^"']+)["'][^>]*>\s*<\/script>\s*/gi, (tag, src) => {
  if (!isLocal(src)) { problems.push('external script not allowed: ' + src); return ''; }
  let js = src === 'data/data.js' ? dataJs : fs.readFileSync(rel(src.split('?')[0]), 'utf8');
  if (/<\/script/i.test(js)) js = js.replace(/<\/script/gi, '<\\/script');
  scripts.push('/* ===== ' + src + ' ===== */\n' + js.trim());
  return scripts.length === 1 ? '@@SCRIPT@@\n' : '';
});
const page = markup
  .replace('@@STYLE@@', () => '<style>\n' + styles.join('\n\n') + '\n</style>')
  .replace('@@SCRIPT@@', () => '<script>\n' + scripts.join('\n;\n') + '\n</script>')
  .trim() + '\n';

// checks
const bare = page.replace(/<script>[\s\S]*?<\/script>/gi, '<script></script>').replace(/<style>[\s\S]*?<\/style>/gi, '<style></style>');
if (/<!doctype|<html[\s>]|<\/html>|<head[\s>]|<\/head>|<body[\s>]|<\/body>/i.test(bare)) problems.push('page.html must not contain doctype/html/head/body tags');
if (!page.startsWith('<title>AAT World</title>')) problems.push('page.html must start with <title>AAT World</title>');
if (!/<meta name="claude:viewport-fit-sides" content="cover">/.test(bare)) problems.push('viewport-fit-sides meta missing');
if ((bare.match(/<style>/g) || []).length !== 1) problems.push('page.html must have exactly ONE <style>');
if ((bare.match(/<script>/g) || []).length !== 1) problems.push('page.html must have exactly ONE <script>');
const ext = (bare.match(/(?:src|href)=["']https?:[^"']+/gi) || []).filter(u => !/fonts\.googleapis\.com/.test(u));
if (ext.length) problems.push('external references other than Google Fonts: ' + ext.join(', '));
// picture paths written literally in code/CSS must exist (data paths are checked by data/verify.js)
const code = styles.join('\n') + scripts.slice(1).join('\n') + bare;
const refs = new Set((code.match(/img\/[A-Za-z0-9_\-\/.]+\.(?:png|jpe?g|svg|webp|gif)/g) || []));
for (const r of refs) if (!fs.existsSync(rel(r))) problems.push('missing picture referenced in code: ' + r);
if (refs.has('img/flags/af.png') && /flags\/af\.png/.test(scripts.slice(1).join('\n') + styles.join('\n'))) problems.push('img/flags/af.png must never be referenced');
const size = Buffer.byteLength(page);
if (size >= 16 * 1024 * 1024) problems.push('page.html is over 16 MB');
writeAtomic(rel('page.html'), page);

/* (c) index.html (local test skeleton = what the publisher wraps around page.html) */
const index = '<!doctype html>\n<html lang="ar" dir="rtl">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
  '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0;font:14px system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>\n' +
  '</head>\n<body>\n' + page + '</body>\n</html>\n';
writeAtomic(rel('index.html'), index);

console.log('data/data.js  ' + kb(Buffer.byteLength(dataJs)) + '  (' + files.length + ' shipped pictures listed)');
console.log('page.html     ' + kb(size) + '  (' + styles.length + ' stylesheets, ' + scripts.length + ' scripts inlined)');
console.log('index.html    ' + kb(Buffer.byteLength(index)));
if (problems.length) { console.log('PROBLEMS:\n- ' + problems.join('\n- ')); process.exitCode = 1; }
else console.log('OK: fragment rules hold (no doctype/html/head/body, starts with <title>, one <style>, one <script>, < 16 MB)');
